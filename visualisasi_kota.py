import pandas as pd
import numpy as np
import statsmodels.api as sm
import plotly.graph_objects as go
from plotly.subplots import make_subplots
import plotly.io as pio

# Memaksa Plotly merender grafik interaktif di sel Google Colab
# pio.renderers.default = 'colab'

# Load Dataset langsung dari GitHub
url = 'https://raw.githubusercontent.com/Alam-A99/DATAAKSI/refs/heads/main/dataset_fiskal_97_hipoFull.csv'
df = pd.read_csv(url)

print(f"Total seluruh data yang dimuat: {len(df)} baris.")

"""# 1. BM Ekonomi vs Pengangguran"""

# 1. SCATTER PLOT MURNI DENGAN GARIS REGRESI
X1 = sm.add_constant(df['bm_ekonomi'])
model1 = sm.OLS(df['PENGANGGURAN'], X1).fit()

x_line1 = np.linspace(df['bm_ekonomi'].min(), df['bm_ekonomi'].max(), 100)
y_line1 = model1.params['const'] + model1.params['bm_ekonomi'] * x_line1

fig1 = go.Figure()

# Titik Scatter Plot
fig1.add_trace(go.Scatter(
    x=df['bm_ekonomi'], y=df['PENGANGGURAN'],
    mode='markers', name='Data Titik (Scatter)',
    marker=dict(size=7, color='#EF553B', opacity=0.7, line=dict(color='white', width=0.5))
))

# Garis Tren
fig1.add_trace(go.Scatter(
    x=x_line1, y=y_line1,
    mode='lines', name=f'Garis Regresi (R²={model1.rsquared:.2f})',
    line=dict(color='#00CC96', width=3)
))

fig1.update_layout(
    title="1. Scatter Plot: BM Ekonomi vs Pengangguran",
    template='plotly_dark',
    xaxis_title='BM Ekonomi',
    yaxis_title='Pengangguran',
    margin=dict(l=40, r=40, b=40, t=50)
)
fig1.show()

"""# 2. Rata-rata Pengangguran Berdasarkan Tingkat BM Perlindungan Sosial"""

# 2. DIAGRAM BATANG (BAR CHART) KATEGORIAL
df['Kategori_BM_Sosial'] = pd.qcut(
    df['bm_perlindungan_sosial'],
    q=3,
    labels=['Sosial Rendah', 'Sosial Sedang', 'Sosial Tinggi']
)

# Hitung Rata-Rata Pengangguran per Kelompok
df_bar2 = df.groupby('Kategori_BM_Sosial')['PENGANGGURAN'].mean().reset_index()

fig2 = go.Figure()

fig2.add_trace(go.Bar(
    x=df_bar2['Kategori_BM_Sosial'],
    y=df_bar2['PENGANGGURAN'],
    text=df_bar2['PENGANGGURAN'].round(2),
    textposition='auto',
    marker_color=['#AB63FA', '#FFA15A', '#19D3F3']
))

fig2.update_layout(
    title="2. Diagram Batang: Rata-rata Pengangguran Berdasarkan Tingkat BM Perlindungan Sosial",
    template='plotly_dark',
    xaxis_title='Kelompok BM Perlindungan Sosial',
    yaxis_title='Rata-Rata Pengangguran',
    margin=dict(l=40, r=40, b=40, t=50)
)
fig2.show()

"""# 3. Perbandingan BM Ekonomi vs BM Sosial (Top 15 Kota)"""

# 3. DIAGRAM BATANG HORISONTAL (DARI SAMPING KIRI)
# Mengambil Top 15 Kota dan diurutkan agar kota terbesar berada di posisi paling atas
df_top15 = (
    df.groupby('Kota')[['bm_ekonomi', 'bm_perlindungan_sosial']]
    .mean()
    .nlargest(15, 'bm_ekonomi')
    .sort_values('bm_ekonomi', ascending=True)
    .reset_index()
)

fig3 = go.Figure()

# Batang BM Ekonomi (Horisontal)
fig3.add_trace(go.Bar(
    y=df_top15['Kota'],
    x=df_top15['bm_ekonomi'],
    name='Rata-Rata BM Ekonomi',
    orientation='h',
    marker_color='#636EFA'
))

# Batang BM Perlindungan Sosial (Horisontal)
fig3.add_trace(go.Bar(
    y=df_top15['Kota'],
    x=df_top15['bm_perlindungan_sosial'],
    name='Rata-Rata BM Sosial',
    orientation='h',
    marker_color='#FF6692'
))

fig3.update_layout(
    title="3. Diagram Batang Horisontal: Perbandingan BM Ekonomi vs BM Sosial (Top 15 Kota)",
    template='plotly_dark',
    barmode='group',
    xaxis_title='Rata-Rata Anggaran',
    yaxis_title='Kota',
    margin=dict(l=120, r=40, b=40, t=50) # Margin kiri diperluas agar nama kota tidak terpotong
)

fig3.show()

"""# 4. Perbandingan Tren Pengangguran Antar Kota"""

# 4. LINE CHART: PERBANDINGAN TREN DARI TAHUN KE TAHUN ANTAR KOTA
# Memilih beberapa kota sampel untuk dibandingkan
kota_pilihan = ['Kota Makassar', 'Kota Salatiga', 'Kota Bandung', 'Kota Medan']

# Filter data berdasarkan kota pilihan dan urutkan berdasarkan tahun
df_line = df[df['Kota'].isin(kota_pilihan)].sort_values('Tahun')

fig4 = go.Figure()

# Warna kustom yang mirip dengan tampilan gambar
warna_kota = {
    'Kota Makassar': '#80CFA9',  # Toska/Hijau Muda
    'Kota Salatiga': '#F2E8A0',  # Kuning
    'Kota Bandung': '#B39DDB',   # Ungu Muda
    'Kota Medan': '#FF8A65'      # Merah/Oranye
}

# Menambahkan garis dan titik untuk masing-masing kota
for kota in kota_pilihan:
    df_kota = df_line[df_line['Kota'] == kota]
    if not df_kota.empty:
        fig4.add_trace(go.Scatter(
            x=df_kota['Tahun'],
            y=df_kota['PENGANGGURAN'],
            mode='lines+markers',
            name=kota,
            marker=dict(size=8),
            line=dict(width=2.5, color=warna_kota.get(kota))
        ))

fig4.update_layout(
    title="4. Perbandingan Tren Pengangguran Antar Kota",
    template='plotly_dark',
    xaxis_title='Tahun',
    yaxis_title='Tingkat Pengangguran',
    legend=dict(
        orientation="h",
        yanchor="bottom",
        y=1.02,
        xanchor="center",
        x=0.5
    ),
    xaxis=dict(
        showgrid=True,
        gridcolor='#444444',
        griddash='dash',
        dtick=1 # Menampilkan setiap tahun di sumbu X
    ),
    yaxis=dict(
        showgrid=True,
        gridcolor='#444444',
        griddash='dash'
    ),
    margin=dict(l=50, r=40, b=40, t=80)
)

fig4.show()
